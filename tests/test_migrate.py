def _tables(conn) -> set[str]:
    cur = conn.cursor()
    cur.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema()"
    )
    return {row[0] for row in cur.fetchall()}


# Recorte do DDL legado de main.py:create_tables() com as colunas que a 001 usa.
# Nenhuma das duas tabelas tem PK/UNIQUE em uuid no main.py.
LEGACY_BASE = [
    """CREATE TABLE IF NOT EXISTS empresa (
        uuid text NOT NULL, cnpj text, razaosocial text, nomefantasia text,
        municipio text, uf text, cnae text, ativo boolean,
        id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY)""",
    "ALTER TABLE empresa ADD COLUMN IF NOT EXISTS regime_tributario text DEFAULT 'MEI'",
    "ALTER TABLE empresa ADD COLUMN IF NOT EXISTS optante_simples boolean DEFAULT true",
    """CREATE TABLE IF NOT EXISTS usuariomei (
        uuid text NOT NULL, email text NOT NULL, senhahash text NOT NULL, nome text,
        empresauuid text, ativo boolean, datacadastro bigint, ultimologin bigint)""",
]


def _legacy_base(conn, *, with_unique_uuid: bool) -> None:
    cur = conn.cursor()
    for sql in LEGACY_BASE:
        cur.execute(sql)
    if with_unique_uuid:
        cur.execute("CREATE UNIQUE INDEX empresa_uuid_key ON empresa (uuid)")
        cur.execute("CREATE UNIQUE INDEX usuariomei_uuid_key ON usuariomei (uuid)")
        cur.execute("INSERT INTO empresa (uuid, cnpj, razaosocial, uf) VALUES ('e1', '1', 'X', 'SP')")
    conn.commit()


@pytest.mark.xfail(
    strict=True,
    reason="001 faz REFERENCES empresa(uuid) e usuariomei(uuid), mas as tabelas legadas "
    "não têm UNIQUE em uuid; correção aditiva prevista na F1",
)
def test_repo_migrations_apply_on_legacy_schema_as_created_by_main(pg_conn):
    _legacy_base(pg_conn, with_unique_uuid=False)
    migrate.migrate(pg_conn)


def test_repo_migrations_apply_once_and_are_idempotent(pg_conn):
    _legacy_base(pg_conn, with_unique_uuid=True)
    first = migrate.migrate(pg_conn)
    assert first == [path.name for path in discover()]
    assert {"fiscal_documents", "fiscal_jobs", "produto_venda_fiscal"} <= _tables(pg_conn)
    cur = pg_conn.cursor()
    cur.execute("SELECT count(*) FROM fiscal_establishments WHERE tenant_id = 'e1'")
    assert cur.fetchone()[0] == 1
    pg_conn.commit()
    assert migrate.migrate(pg_conn) == []
    # O SQL em si também precisa ser reexecutável (IF NOT EXISTS etc.).
    cur = pg_conn.cursor()
    for path in discover():
        cur.execute(path.read_text(encoding="utf-8"))
    pg_conn.rollback()


def test_dry_run_writes_nothing(pg_conn):
    pending = migrate.migrate(pg_conn, dry_run=True)
    assert pending == [path.name for path in discover()]
    assert _tables(pg_conn) == set()


def test_failed_migration_rolls_back_only_itself_and_releases_lock(pg_conn, tmp_path):
    _write(tmp_path, "001_ok.sql", "CREATE TABLE IF NOT EXISTS ok_table (id INT);")
    _write(
        tmp_path,
        "002_broken.sql",
        "CREATE TABLE IF NOT EXISTS half_table (id INT);\nSELECT * FROM missing_table;",
    )
    with pytest.raises(Exception, match="missing_table"):
        migrate.migrate(pg_conn, root=tmp_path)
    assert _tables(pg_conn) == {"ok_table", "schema_migrations"}
    cur = pg_conn.cursor()
    cur.execute("SELECT version FROM schema_migrations")
    assert [row[0] for row in cur.fetchall()] == ["001_ok.sql"]
    cur.execute("SELECT pg_try_advisory_lock(%s)", (ADVISORY_LOCK_KEY,))
    assert cur.fetchone()[0] is True
    cur.execute("SELECT pg_advisory_unlock(%s)", (ADVISORY_LOCK_KEY,))
    pg_conn.commit()


def test_waits_for_advisory_lock_held_by_another_replica(pg_conn, tmp_path):
    import os

    import psycopg2

    _write(tmp_path, "001_ok.sql", "CREATE TABLE IF NOT EXISTS ok_table (id INT);")
    other = psycopg2.connect(os.environ["SERVER_MEI_TEST_DSN"])
    other.autocommit = True
    other.cursor().execute("SELECT pg_advisory_lock(%s)", (ADVISORY_LOCK_KEY,))
    result = {}
    worker = threading.Thread(
        target=lambda: result.setdefault("done", migrate.migrate(pg_conn, root=tmp_path))
    )
    worker.start()
    worker.join(timeout=0.5)
    assert worker.is_alive(), "migrate deveria esperar o lock da outra réplica"
    other.cursor().execute("SELECT pg_advisory_unlock(%s)", (ADVISORY_LOCK_KEY,))
    worker.join(timeout=10)
    other.close()
    assert result["done"] == ["001_ok.sql"]
